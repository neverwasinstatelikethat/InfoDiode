def get_parameter_range(param_type: ParameterType) -> ParameterRange:
    """Возвращает диапазон значений для типа параметра."""
    return PARAMETER_TYPE_TABLE[param_type]["range"]  # type: ignore


def validate_value_in_range(value: float, param_type: ParameterType) -> tuple[bool, str]:
    """Проверяет, что значение в допустимом диапазоне."""
    range_info = get_parameter_range(param_type)
    min_val = range_info["min"]
    max_val = range_info["max"]

    if value < min_val:
        return False, f"Значение {value} ниже минимума {min_val}"
    if value > max_val:
        return False, f"Значение {value} выше максимума {max_val}"
    return True, "В допустимом диапазоне"