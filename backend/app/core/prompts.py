def _build_table_system_prompt(parameter_table: list[dict]) -> str:
    """Строит системный промпт для режима с таблицей."""
    lines = [
        "Ты — эксперт по SCADA мнемосхемам.",
        "",
        "## ЗАДАЧА",
        "Найди на экране ТОЛЬКО параметры из таблицы ниже.",
        "",
        "## ПРАВИЛА",
        "• Ищи ТОЛЬКО параметры из таблицы",
        "• НЕ придумывай параметры, которых нет в таблице",
        "• Указывай ID параметра из таблицы",
        "• Если параметр НЕ виден — НЕ включай",
        "• value=0.0 — нормально, включай!",
        "",
        "## ТАБЛИЦА ПАРАМЕТРОВ",
        "",
        "| ID | Название | Ед. |",
        "| ID | Название | Тип | Ед. |",
        "|----|----------|-----|-----|",
    ]
    
    for param in parameter_table:  # Ограничиваем для контекста
        pid = param.get("id", "")
        name = param.get("name", param.get("label", ""))
        ptype = param.get("type", param.get("param_type", ""))
        unit = param.get("unit", "")
        lines.append(f"| {pid} | {name[:40]} | {ptype} | {unit} |")
    
    lines.extend([
        "",
        "## ФОРМАТ ВЫВОДА",
        "Выведи ТОЛЬКО JSON:",
        '{"parameters":[{"id":1,"label":"...","value":"...","unit":"...","param_type":"..."}]}',
    ])
    
    return "\n".join(lines)


def _format_few_shot() -> str:
    """Форматирует few-shot примеры."""
    parts = []
    for i, example in enumerate(FEW_SHOT_EXAMPLES, 1):
        parts.append(f"Пример {i}: {example['description']}")
        import json
        parts.append(json.dumps(example['output'], ensure_ascii=False, indent=2))
    return "\n\n".join(parts)


