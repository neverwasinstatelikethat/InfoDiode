def build_messages(
    frame_timestamp: str,
    additional_context: str = "",
    parameter_table: list[dict] | None = None,
    include_few_shot: bool = False,
) -> tuple[str, str]:
    """Собирает системный и пользовательский промпты для VLM (полный кадр).

    Args:
        frame_timestamp: Временная метка кадра в формате HH:MM:SS.mmm.
        additional_context: Дополнительный контекст.
        parameter_table: Таблица параметров из CSV/Excel.
        include_few_shot: Включить few-shot примеры.

    Returns:
        Кортеж (system_prompt, user_prompt).
    """
    if parameter_table:
        # Режим с таблицей — строгий поиск
        system_prompt = _build_table_system_prompt(parameter_table)
        user_prompt = USER_PROMPT_TABLE_TEMPLATE.replace("{{timestamp}}", frame_timestamp)
    else:
        # Стандартный режим — поиск всех параметров
        system_prompt = SYSTEM_PROMPT
        if include_few_shot:
            system_prompt += "\n\n## ПРИМЕРЫ\n\n" + _format_few_shot()
        
        context = additional_context if additional_context else "Автоматический анализ мнемосхемы SCADA"
        user_prompt = USER_PROMPT_TEMPLATE.replace("{{timestamp}}", frame_timestamp).replace("{{additional_context}}", context)

    return system_prompt, user_prompt


